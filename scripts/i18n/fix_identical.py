# Load current translations
translations_path = Path('scripts/i18n/output/translations.jsonl')
all_translations = []
with open(translations_path) as f:
    for line in f:
        all_translations.append(json.loads(line))

# Build index by ID
trans_by_id = {t['id']: i for i, t in enumerate(all_translations)}

# Update the identical-to-source translations
updated_count = 0
not_found = []
for entry in all_translations:
    src = entry['source_text']
    if src in TRANSLATIONS and entry['translation'] == src:
        entry['translation'] = TRANSLATIONS[src]
        updated_count += 1

# Check if any TRANSLATIONS keys weren't matched
matched_sources = set()
for entry in all_translations:
    if entry['source_text'] in TRANSLATIONS:
        matched_sources.add(entry['source_text'])

unmatched = set(TRANSLATIONS.keys()) - matched_sources
if unmatched:
    print(f"WARNING: {len(unmatched)} translation keys not found in translations.jsonl")
    for u in list(unmatched)[:5]:
        print(f"  {repr(u)}")

# Write back
with open(translations_path, 'w') as f:
    for entry in all_translations:
        f.write(json.dumps(entry, ensure_ascii=False) + '\n')

print(f"Updated {updated_count} translations in translations.jsonl")
print(f"Total entries: {len(all_translations)}")
